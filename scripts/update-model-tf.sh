#!/usr/bin/env bash
set -euo pipefail

if [[ $# -ne 1 || ! "$1" =~ ^[0-9a-f]{40}$ ]]; then
  echo "usage: $0 <40-character model-tf commit SHA>" >&2
  exit 2
fi

sha="$1"
script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
repo_root="$(cd "$script_dir/.." && pwd)"
tmp_dir="$(mktemp -d)"
trap 'rm -rf "$tmp_dir"' EXIT

base="https://raw.githubusercontent.com/deximple/model-tf/$sha"
curl --fail --silent --show-error "$base/model-facts.json" -o "$tmp_dir/model-facts.json"
curl --fail --silent --show-error "$base/model-tiers.json" -o "$tmp_dir/model-tiers.json"

python3 - "$sha" "$tmp_dir/model-facts.json" "$tmp_dir/model-tiers.json" \
  "$repo_root/Sources/SwitcherCore/Suggestion/ModelTFSnapshot.swift" <<'PY'
from pathlib import Path
import sys

sha, facts_path, tiers_path, output_path = sys.argv[1:]
facts = Path(facts_path).read_text(encoding="utf-8")
tiers = Path(tiers_path).read_text(encoding="utf-8")

def literal(value):
    count = 1
    while f'"""{"#" * count}' in value or f'\\{"#" * count}(' in value:
        count += 1
    hashes = "#" * count
    return f'{hashes}"""\n{value.rstrip()}\n"""{"#" * count}'

source = f'''// Generated by scripts/update-model-tf.sh; do not edit.
enum ModelTFSnapshot {{
    static let commit = "{sha}"
    static let facts = {literal(facts)}
    static let tiers = {literal(tiers)}
}}
'''
Path(output_path).write_text(source, encoding="utf-8")
PY
